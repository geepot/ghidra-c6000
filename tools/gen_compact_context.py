#!/usr/bin/env python3
"""Mirror the insn16 token fields onto big-endian context bits 32-47 (issue #31).

A compact word holds its first instruction in the 16 LSBs (SPRUFE8B 3.10.2.3,
Table 3-16), at byte offset +2 in big-endian memory, but a SLEIGH token is read
at the slot's own address. C6000PacketContext copies each BE slot's halfword
into c_h16; these fields decode it. Context bits count from the MSB, so token
bit b is context bit 47-b.
"""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]/"data/languages"
text=(root/"c6000.sinc").read_text()
block=re.search(r"define token insn16 \(16\)\n(.*?)\n;",text,re.S).group(1)
lines=["# Generated by tools/gen_compact_context.py from the insn16 token. Apache-2.0.",
       "  c_h16=(32,47) noflow"]
for name,lo,hi,signed in re.findall(r"(\w+)=\((\d+),(\d+)\)( signed)?",block):
    lines.append(f"  {name}=({47-int(hi)},{47-int(lo)}){signed} noflow")
(root/"c6000_compact_context.sinc").write_text("\n".join(lines)+"\n")
