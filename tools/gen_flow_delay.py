#!/usr/bin/env python3
"""Generate constant SLEIGH delay-byte choices for late proven return windows.

SPRUFE8B 3.5 / 4.2.6; SLEIGH 7.11 counts bytes, not cycles/instructions.
"""
from pathlib import Path
p=Path(__file__).resolve().parents[1]/"data/languages/c6000_flow_delay.sinc"
lines=["# Generated by tools/gen_flow_delay.py. Apache-2.0.",
       "# SPRUFE8B 3.5 and 4.2.6; SLEIGH 7.11: operand is minimum byte count."]
for n in range(0,256,2):
    body=f" delayslot({n});" if n else ""
    # A staged write waiting on this branch's own reads is committed here, after them (c6000.sinc StageCommit).
    lines.append(f"CFlowDelay: is c_inert=0 & c_flow_delay={n} & StageCommit1 & StageCommit2 {{ build StageCommit1; build StageCommit2;{body} }}")
# A latched branch ends here, after any branch that lands behind it; the instruction it lands after transfers (c6000.sinc Land).
lines.append("CFlowDelay: is c_inert=1 & Land1 & Land2 { build Land1; build Land2; goto inst_next; }")
p.write_text("\n".join(lines)+"\n")
