#!/usr/bin/env python3
"""Generate the SLEIGH tables that pick a staging or latch register from a context field.

`attach variables` would do this, but Ghidra then treats the attached context field as
following flow, whatever `noflow` says, so one instruction's value would reach the next.
"""
from pathlib import Path

p = Path(__file__).resolve().parents[1] / "data/languages/c6000_stage.sinc"
lines = ["# Generated by tools/gen_stage.py. Apache-2.0.",
         "# The held result of a staged write (SPRUFE8B 3.5) and the latched target of a branch (3.5, 4.2.6)."]
registers = [f"A{n}" for n in range(32)] + [f"B{n}" for n in range(32)]
for table, field, prefix in (("DeferReg", "c_defer_reg", ""), ("DeferNew", "c_defer_reg", "C6000_NEW_"),
                             ("Cm1Reg", "c_cm1_reg", ""), ("Cm1New", "c_cm1_reg", "C6000_NEW_"),
                             ("Cm2Reg", "c_cm2_reg", ""), ("Cm2New", "c_cm2_reg", "C6000_NEW_")):
    for index, name in enumerate(registers):
        lines.append(f"{table}: is {field}={index} {{ export {prefix}{name}; }}")
for table, field, prefix in (("LatchT", "c_latch_t", "C6000_LATCH_T"), ("LatchPc", "c_latch_t", "C6000_LATCH_PC"),
                             ("Land1T", "c_land1_t", "C6000_LATCH_T"), ("Land1Pc", "c_land1_t", "C6000_LATCH_PC"),
                             ("Land2T", "c_land2_t", "C6000_LATCH_T"), ("Land2Pc", "c_land2_t", "C6000_LATCH_PC")):
    for index in range(4):
        lines.append(f"{table}: is {field}={index} {{ export {prefix}{index}; }}")
p.write_text("\n".join(lines) + "\n")
