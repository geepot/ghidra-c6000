#!/usr/bin/env python3
"""Generate the latched forms of the 32-bit B and BNOP constructors.

A latched branch records its predicate, and its register target, as it issues and holds no
transfer; the instruction it lands behind carries that (c6000.sinc Land). Each form here is the
ordinary constructor's own pattern with c_inert_wrap=0 replaced by 1 or 2, so the two are
disjoint and the latched one can never drift from the encoding it replaces (SPRUFE8B 3.5, 4.2.6).
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1] / "data/languages"
lines = ["# Generated by tools/gen_latched.py. Apache-2.0.",
         "# Latched forms of the 32-bit B and BNOP constructors; see c6000.sinc."]
count = 0
for source in ("c6000_decode.sinc", "c6000_manual.sinc"):
    text = "\n".join(line for line in (ROOT / source).read_text().split("\n") if not line.lstrip().startswith("#"))
    for display, pattern in re.findall(r'^:([^\n]*?)\s+is\s+(.*?)\{', text, re.S | re.M):
        name = re.match(r'(\^Cond\^)?"?(BNOP|B)\.S[12]"?(\s|$)', display.strip())
        if not name or "IRP" in display or "NRP" in display:
            continue
        pattern = " ".join(pattern.split())
        terms = [term.strip() for term in re.split(r'\s&\s(?![^()]*\))', pattern)
                 if term.strip() not in ("CFlowDelay", "c_inert_wrap=0")]
        register = "Src2" in display
        latch = "LatchT = zext(Cond);" if "Cond" in terms else "LatchT = 1;"
        if register:
            latch += " LatchPc = Src2;"
        extra = ["c_inert_wrap=%d" % (2 if register else 1), "LatchT", "StageCommit1", "StageCommit2", "Land1", "Land2"]
        if register:
            extra.append("LatchPc")
        lines.append(":%s is %s & %s\n{ %s build StageCommit1; build StageCommit2; build Land1; build Land2; }"
                     % (display.strip(), " & ".join(terms), " & ".join(extra), latch))
        count += 1
(ROOT / "c6000_latched.sinc").write_text("\n".join(lines) + "\n")
print("wrote c6000_latched.sinc (%d forms)" % count)
